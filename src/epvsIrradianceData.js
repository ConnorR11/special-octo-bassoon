// Postcode district mapping supplied for the Scottish EPVS application.
export function getEpvsZone(postcode) {
  const value = String(postcode || "")
    .toUpperCase()
    .replace(/\s+/g, "")
    .trim()

  const match = value.match(/^([A-Z]{1,2})(\d{1,2})/)
  if (!match) return null

  const letters = match[1]
  const number = Number(match[2])

  if (letters === "AB") return "16"
  if (letters === "DD") return "15"
  if (letters === "DG") return "8S"

  if (letters === "EH") {
    if (number >= 43 && number <= 46) return "9S"
    if ((number >= 1 && number <= 42) || number >= 47) return "15"
    return null
  }

  if (letters === "FK") return "14"
  if (letters === "G") return "14"
  if (letters === "KA") return "14"
  if (letters === "KY") return "15"
  if (letters === "ML") return "14"
  if (letters === "PA") return "14"

  if (letters === "IV") {
    if ([30, 31, 32, 36].includes(number)) return "16"
    if ((number >= 1 && number <= 29) || (number >= 40 && number <= 56) || number === 63) return "17"
    return null
  }

  if (letters === "KW") {
    if (number >= 15 && number <= 17) return "19"
    if (number >= 1 && number <= 14) return "17"
    return null
  }

  if (letters === "PH") {
    if (number === 26) return "16"
    if (number === 49 || number === 50) return "14"
    if ((number >= 1 && number <= 18) || (number >= 2 && number <= 18)) return "15"
    if ((number >= 19 && number <= 25) || (number >= 30 && number <= 44)) return "17"
    return null
  }

  if (letters === "TD") {
    if (number === 12 || number === 15) return "9E"
    if (number >= 1 && number <= 11 || number >= 13 && number <= 14) return "9S"
    return null
  }

  return null
}

function clamp(value, min, max) {
  return Math.min(max, Math.max(min, value))
}

/**
 * Return the EPVS Kk / irradiance figure for a pitch and orientation.
 * The workbook provides pitch at 1° increments and orientation at 5° increments.
 * For an orientation between two workbook columns we linearly interpolate.
 * 180° is treated as equivalent to 0° (due south in the opposite direction is
 * represented by the workbook's 0° endpoint convention).
 */
export function getIrradiance(zoneCode, pitch, orientation) {
  const zoneName = ZONE_NAMES[String(zoneCode || "").toUpperCase()]
  const values = IRRADIANCE_DATA[zoneName]
  if (!values) return 0

  const safePitch = clamp(Math.round(Number(pitch) || 0), 0, 90)
  let safeOrientation = Math.abs(Number(orientation) || 0)
  safeOrientation = clamp(safeOrientation, 0, 180)

  if (safeOrientation === 180) safeOrientation = 0

  const rowOffset = safePitch * ORIENTATIONS.length
  const lowerOrientation = Math.floor(safeOrientation / 5) * 5
  const upperOrientation = Math.min(175, lowerOrientation + 5)
  const lowerIndex = Math.round(lowerOrientation / 5)
  const upperIndex = Math.round(upperOrientation / 5)

  const lowerValue = Number(values[rowOffset + lowerIndex] || 0)
  const upperValue = Number(values[rowOffset + upperIndex] || lowerValue)

  if (lowerIndex === upperIndex) return lowerValue

  const fraction = (safeOrientation - lowerOrientation) / 5
  return lowerValue + (upperValue - lowerValue) * fraction
}

export function getEpvsZoneName(zoneCode) {
  return ZONE_NAMES[String(zoneCode || "").toUpperCase()] || null
}
